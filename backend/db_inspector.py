import psycopg2
from psycopg2.extras import DictCursor

def get_object_counts(conn):
    """
    Returns a dictionary of object counts: tables, views, functions, sequences, triggers.
    This is extremely fast and suitable for pre-flight ETA calculations.
    """
    counts = {
        'tables': 0,
        'views': 0,
        'functions': 0,
        'sequences': 0,
        'triggers': 0
    }
    
    with conn.cursor(cursor_factory=DictCursor) as cur:
        # Count Tables, Views, Sequences
        cur.execute("""
            SELECT relkind, count(*) 
            FROM pg_class c
            JOIN pg_namespace n ON n.oid = c.relnamespace
            WHERE n.nspname NOT IN ('pg_catalog', 'information_schema', 'pg_toast')
            GROUP BY relkind;
        """)
        for row in cur.fetchall():
            kind = row['relkind']
            count = row['count']
            if kind == 'r': counts['tables'] += count
            elif kind == 'v': counts['views'] += count
            elif kind == 'S': counts['sequences'] += count
            elif kind == 'm': counts['views'] += count # materialized views
            
        # Count Functions/Procedures
        cur.execute("""
            SELECT count(*) 
            FROM pg_proc p
            JOIN pg_namespace n ON n.oid = p.pronamespace
            WHERE n.nspname NOT IN ('pg_catalog', 'information_schema', 'pg_toast');
        """)
        counts['functions'] = cur.fetchone()[0]
        
        # Count Triggers (excluding internal ones generated by FKs)
        cur.execute("""
            SELECT count(*) 
            FROM pg_trigger t
            JOIN pg_class c ON c.oid = t.tgrelid
            JOIN pg_namespace n ON n.oid = c.relnamespace
            WHERE n.nspname NOT IN ('pg_catalog', 'information_schema', 'pg_toast')
            AND t.tgisinternal = false;
        """)
        counts['triggers'] = cur.fetchone()[0]
        
    return counts

def get_schema_snapshot(conn, scope):
    """
    Extracts comprehensive metadata for the selected scope.
    """
    snapshot = {
        'tables': {},
        'views': {},
        'functions': {},
        'sequences': {},
        'triggers': {}
    }
    
    with conn.cursor(cursor_factory=DictCursor) as cur:
        # Tables and Columns
        if scope.get('tables'):
            # Get tables
            cur.execute("""
                SELECT c.relname as table_name
                FROM pg_class c
                JOIN pg_namespace n ON n.oid = c.relnamespace
                WHERE n.nspname NOT IN ('pg_catalog', 'information_schema', 'pg_toast')
                AND c.relkind = 'r';
            """)
            tables = [row['table_name'] for row in cur.fetchall()]
            
            for t in tables:
                snapshot['tables'][t] = {'columns': {}, 'indexes': {}}
                
                # Get columns
                cur.execute("""
                    SELECT column_name, data_type, character_maximum_length, column_default, is_nullable
                    FROM information_schema.columns 
                    WHERE table_schema NOT IN ('pg_catalog', 'information_schema')
                    AND table_name = %s;
                """, (t,))
                for col in cur.fetchall():
                    type_str = col['data_type']
                    if col['character_maximum_length']:
                        type_str += f"({col['character_maximum_length']})"
                    
                    snapshot['tables'][t]['columns'][col['column_name']] = {
                        'type': type_str,
                        'default': col['column_default'],
                        'nullable': col['is_nullable']
                    }
                    
                # Get indexes
                cur.execute("""
                    SELECT indexname, indexdef
                    FROM pg_indexes
                    WHERE schemaname NOT IN ('pg_catalog', 'information_schema')
                    AND tablename = %s;
                """, (t,))
                for idx in cur.fetchall():
                    snapshot['tables'][t]['indexes'][idx['indexname']] = idx['indexdef']
                    
        # Views
        if scope.get('views'):
            cur.execute("""
                SELECT table_name, view_definition
                FROM information_schema.views
                WHERE table_schema NOT IN ('pg_catalog', 'information_schema');
            """)
            for row in cur.fetchall():
                snapshot['views'][row['table_name']] = row['view_definition']
                
        # Functions
        if scope.get('functions'):
            cur.execute("""
                SELECT p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')' as signature,
                       pg_get_functiondef(p.oid) as def
                FROM pg_proc p
                JOIN pg_namespace n ON n.oid = p.pronamespace
                WHERE n.nspname NOT IN ('pg_catalog', 'information_schema', 'pg_toast');
            """)
            for row in cur.fetchall():
                snapshot['functions'][row['signature']] = row['def']
                
        # Sequences
        if scope.get('sequences'):
            cur.execute("""
                SELECT sequence_name
                FROM information_schema.sequences
                WHERE sequence_schema NOT IN ('pg_catalog', 'information_schema');
            """)
            for row in cur.fetchall():
                snapshot['sequences'][row['sequence_name']] = "EXISTS"
                
        # Triggers
        if scope.get('triggers'):
            cur.execute("""
                SELECT t.tgname, pg_get_triggerdef(t.oid) as def
                FROM pg_trigger t
                JOIN pg_class c ON c.oid = t.tgrelid
                JOIN pg_namespace n ON n.oid = c.relnamespace
                WHERE n.nspname NOT IN ('pg_catalog', 'information_schema', 'pg_toast')
                AND t.tgisinternal = false;
            """)
            for row in cur.fetchall():
                snapshot['triggers'][row['tgname']] = row['def']
                
    return snapshot
