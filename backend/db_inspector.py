import psycopg2
from psycopg2.extras import DictCursor

def get_object_counts(conn):
    """
    Returns a dictionary of object counts: tables, views, materialized views,
    functions, procedures, sequences, triggers, roles, and grants,
    plus a list of user table names.
    This is extremely fast and suitable for pre-flight ETA calculations.
    """
    counts = {
        'tables': 0,
        'views': 0,
        'materialized_views': 0,
        'functions': 0,
        'procedures': 0,
        'sequences': 0,
        'triggers': 0,
        'roles': 0,
        'grants': 0,
        'table_names': []
    }
    
    with conn.cursor(cursor_factory=DictCursor) as cur:
        # 1. Count Tables, Views, Materialized Views, Sequences & get table names
        cur.execute("""
            SELECT relname, relkind
            FROM pg_class c
            JOIN pg_namespace n ON n.oid = c.relnamespace
            WHERE n.nspname NOT IN ('pg_catalog', 'information_schema', 'pg_toast')
            AND relkind IN ('r', 'v', 'S', 'm');
        """)
        for row in cur.fetchall():
            kind = row['relkind']
            name = row['relname']
            if kind == 'r':
                counts['tables'] += 1
                counts['table_names'].append(name)
            elif kind == 'v':
                counts['views'] += 1
            elif kind == 'm':
                counts['materialized_views'] += 1
            elif kind == 'S':
                counts['sequences'] += 1
            
        # 2. Count Functions vs Procedures
        try:
            cur.execute("""
                SELECT prokind, count(*)
                FROM pg_proc p
                JOIN pg_namespace n ON n.oid = p.pronamespace
                WHERE n.nspname NOT IN ('pg_catalog', 'information_schema', 'pg_toast')
                GROUP BY prokind;
            """)
            for row in cur.fetchall():
                pk = row['prokind']
                cnt = row['count']
                if pk == 'p':
                    counts['procedures'] += cnt
                else: # 'f', 'a', 'w'
                    counts['functions'] += cnt
        except Exception:
            # Fallback if prokind not available
            conn.rollback()
            cur.execute("""
                SELECT count(*) 
                FROM pg_proc p
                JOIN pg_namespace n ON n.oid = p.pronamespace
                WHERE n.nspname NOT IN ('pg_catalog', 'information_schema', 'pg_toast');
            """)
            counts['functions'] = cur.fetchone()[0]
        
        # 3. Count Triggers (excluding internal ones generated by FKs)
        cur.execute("""
            SELECT count(*) 
            FROM pg_trigger t
            JOIN pg_class c ON c.oid = t.tgrelid
            JOIN pg_namespace n ON n.oid = c.relnamespace
            WHERE n.nspname NOT IN ('pg_catalog', 'information_schema', 'pg_toast')
            AND t.tgisinternal = false;
        """)
        counts['triggers'] = cur.fetchone()[0]

        # 4. Count Custom Roles / Users
        try:
            cur.execute("""
                SELECT count(*) 
                FROM pg_roles 
                WHERE rolname NOT LIKE 'pg_%' 
                  AND rolname NOT IN ('postgres');
            """)
            counts['roles'] = cur.fetchone()[0]
        except Exception:
            conn.rollback()
            counts['roles'] = 0

        # 5. Count Grants / Privileges
        try:
            cur.execute("""
                SELECT count(*)
                FROM information_schema.role_table_grants
                WHERE table_schema NOT IN ('pg_catalog', 'information_schema')
                  AND grantee NOT LIKE 'pg_%';
            """)
            counts['grants'] = cur.fetchone()[0]
        except Exception:
            conn.rollback()
            counts['grants'] = 0
        
    return counts

def format_column_type(col_data):
    """Formats full canonical SQL type (e.g. varchar(50), numeric(10,2))."""
    dt = col_data['data_type']
    char_len = col_data.get('character_maximum_length')
    num_prec = col_data.get('numeric_precision')
    num_scale = col_data.get('numeric_scale')
    
    if char_len:
        if dt.lower() in ('character varying', 'varchar'):
            return f"varchar({char_len})"
        return f"{dt}({char_len})"
    if dt.lower() in ('numeric', 'decimal') and num_prec is not None:
        if num_scale is not None and num_scale > 0:
            return f"{dt}({num_prec},{num_scale})"
        return f"{dt}({num_prec})"
    return dt

def get_schema_snapshot(conn, scope):
    """
    Extracts comprehensive metadata for the selected scope.
    Includes tables, views, materialized views, functions, procedures,
    sequences, triggers, roles, and grants.
    """
    snapshot = {
        'tables': {},
        'views': {},
        'materialized_views': {},
        'functions': {},
        'procedures': {},
        'sequences': {},
        'triggers': {},
        'roles': {},
        'grants': {}
    }
    
    with conn.cursor(cursor_factory=DictCursor) as cur:
        # Tables and Columns
        if scope.get('tables'):
            cur.execute("""
                SELECT c.relname as table_name
                FROM pg_class c
                JOIN pg_namespace n ON n.oid = c.relnamespace
                WHERE n.nspname NOT IN ('pg_catalog', 'information_schema', 'pg_toast')
                AND c.relkind = 'r'
                ORDER BY c.relname;
            """)
            tables = [row['table_name'] for row in cur.fetchall()]
            
            for t in tables:
                snapshot['tables'][t] = {'columns': {}, 'indexes': {}, 'primary_keys': []}
                
                # Get primary keys
                cur.execute("""
                    SELECT kcu.column_name
                    FROM information_schema.table_constraints tc
                    JOIN information_schema.key_column_usage kcu
                      ON tc.constraint_name = kcu.constraint_name
                      AND tc.table_schema = kcu.table_schema
                    WHERE tc.constraint_type = 'PRIMARY KEY'
                      AND tc.table_schema NOT IN ('pg_catalog', 'information_schema')
                      AND tc.table_name = %s
                    ORDER BY kcu.ordinal_position;
                """, (t,))
                pks = [row['column_name'] for row in cur.fetchall()]
                snapshot['tables'][t]['primary_keys'] = pks
                
                # Get columns
                cur.execute("""
                    SELECT column_name, data_type, character_maximum_length, 
                           numeric_precision, numeric_scale, column_default, is_nullable,
                           ordinal_position
                    FROM information_schema.columns 
                    WHERE table_schema NOT IN ('pg_catalog', 'information_schema')
                    AND table_name = %s
                    ORDER BY ordinal_position;
                """, (t,))
                for col in cur.fetchall():
                    type_str = format_column_type(col)
                    c_name = col['column_name']
                    snapshot['tables'][t]['columns'][c_name] = {
                        'type': type_str,
                        'default': col['column_default'],
                        'nullable': col['is_nullable'],
                        'is_pk': c_name in pks,
                        'ordinal_position': col['ordinal_position']
                    }
                    
                # Get indexes
                cur.execute("""
                    SELECT indexname, indexdef
                    FROM pg_indexes
                    WHERE schemaname NOT IN ('pg_catalog', 'information_schema')
                    AND tablename = %s
                    ORDER BY indexname;
                """, (t,))
                for idx in cur.fetchall():
                    snapshot['tables'][t]['indexes'][idx['indexname']] = idx['indexdef']
                    
        # Views
        if scope.get('views'):
            cur.execute("""
                SELECT table_name, view_definition
                FROM information_schema.views
                WHERE table_schema NOT IN ('pg_catalog', 'information_schema')
                ORDER BY table_name;
            """)
            for row in cur.fetchall():
                snapshot['views'][row['table_name']] = row['view_definition'].strip()

        # Materialized Views
        if scope.get('materialized_views'):
            cur.execute("""
                SELECT c.relname as matview_name, pg_get_viewdef(c.oid) as def
                FROM pg_class c
                JOIN pg_namespace n ON n.oid = c.relnamespace
                WHERE n.nspname NOT IN ('pg_catalog', 'information_schema', 'pg_toast')
                AND c.relkind = 'm'
                ORDER BY c.relname;
            """)
            for row in cur.fetchall():
                snapshot['materialized_views'][row['matview_name']] = row['def'].strip()
                
        # Functions & Procedures
        if scope.get('functions') or scope.get('procedures'):
            try:
                cur.execute("""
                    SELECT p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')' as signature,
                           pg_get_functiondef(p.oid) as def,
                           p.prokind
                    FROM pg_proc p
                    JOIN pg_namespace n ON n.oid = p.pronamespace
                    WHERE n.nspname NOT IN ('pg_catalog', 'information_schema', 'pg_toast')
                    ORDER BY signature;
                """)
                for row in cur.fetchall():
                    sig = row['signature']
                    fn_def = row['def'].strip()
                    pk = row['prokind']
                    if pk == 'p' and scope.get('procedures'):
                        snapshot['procedures'][sig] = fn_def
                    elif pk != 'p' and scope.get('functions'):
                        snapshot['functions'][sig] = fn_def
            except Exception:
                # Fallback
                conn.rollback()
                if scope.get('functions'):
                    cur.execute("""
                        SELECT p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')' as signature,
                               pg_get_functiondef(p.oid) as def
                        FROM pg_proc p
                        JOIN pg_namespace n ON n.oid = p.pronamespace
                        WHERE n.nspname NOT IN ('pg_catalog', 'information_schema', 'pg_toast')
                        ORDER BY signature;
                    """)
                    for row in cur.fetchall():
                        snapshot['functions'][row['signature']] = row['def'].strip()
                
        # Sequences
        if scope.get('sequences'):
            cur.execute("""
                SELECT sequence_name
                FROM information_schema.sequences
                WHERE sequence_schema NOT IN ('pg_catalog', 'information_schema')
                ORDER BY sequence_name;
            """)
            for row in cur.fetchall():
                snapshot['sequences'][row['sequence_name']] = "EXISTS"
                
        # Triggers
        if scope.get('triggers'):
            cur.execute("""
                SELECT t.tgname, pg_get_triggerdef(t.oid) as def, c.relname as table_name
                FROM pg_trigger t
                JOIN pg_class c ON c.oid = t.tgrelid
                JOIN pg_namespace n ON n.oid = c.relnamespace
                WHERE n.nspname NOT IN ('pg_catalog', 'information_schema', 'pg_toast')
                AND t.tgisinternal = false
                ORDER BY t.tgname;
            """)
            for row in cur.fetchall():
                snapshot['triggers'][row['tgname']] = {
                    'def': row['def'].strip(),
                    'table': row['table_name']
                }

        # Roles / Users
        if scope.get('roles') or scope.get('users'):
            try:
                cur.execute("""
                    SELECT rolname, rolcanlogin, rolsuper, rolinherit, rolcreaterole, rolcreatedb, rolconnlimit
                    FROM pg_roles
                    WHERE rolname NOT LIKE 'pg_%'
                      AND rolname NOT IN ('postgres')
                    ORDER BY rolname;
                """)
                for row in cur.fetchall():
                    snapshot['roles'][row['rolname']] = {
                        'can_login': bool(row['rolcanlogin']),
                        'superuser': bool(row['rolsuper']),
                        'inherit': bool(row['rolinherit']),
                        'create_role': bool(row['rolcreaterole']),
                        'create_db': bool(row['rolcreatedb']),
                        'conn_limit': row['rolconnlimit']
                    }
            except Exception:
                conn.rollback()

        # Grants / Permissions
        if scope.get('grants'):
            try:
                cur.execute("""
                    SELECT grantee, table_name, privilege_type, is_grantable
                    FROM information_schema.role_table_grants
                    WHERE table_schema NOT IN ('pg_catalog', 'information_schema')
                      AND grantee NOT LIKE 'pg_%'
                    ORDER BY grantee, table_name, privilege_type;
                """)
                for row in cur.fetchall():
                    grant_key = f"{row['grantee']} ON {row['table_name']} ({row['privilege_type']})"
                    snapshot['grants'][grant_key] = {
                        'grantee': row['grantee'],
                        'object_type': 'TABLE',
                        'object_name': row['table_name'],
                        'privilege': row['privilege_type'],
                        'grantable': row['is_grantable'] == 'YES'
                    }
            except Exception:
                conn.rollback()
                
    return snapshot
